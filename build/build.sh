#!/bin/bash
#
# Builds Hecate.app.
#
#   ./build/build.sh
#
# Three things happen that are not obvious:
#
# 1. The API key is copied out of .env into a generated module that gets
#    frozen into the bundle, so the tester never has to hold a key. That
#    module is gitignored — it must never be committed.
#
# 2. The app is built against the Homebrew Python in .buildvenv, NOT the
#    project's .venv. The project venv runs on Xcode's bundled Python, which
#    has no shared libpython and lives inside Xcode.app; PyInstaller cannot
#    freeze it, and an app built from it would depend on a file the target
#    Mac does not have.
#
# 3. The finished bundle is ad-hoc signed. This does not make it trusted, but
#    it decides WHICH refusal the user sees. A valid ad-hoc signature turns
#    the fatal "app is damaged, move to Trash" dialog into "unidentified
#    developer", which has an Open Anyway button in System Settings. Without
#    it there is no recovery path that does not involve a terminal.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

PY=".buildvenv/bin/python"
APP="dist/Hecate.app"

if [ ! -x "$PY" ]; then
  echo "Build environment missing. Create it with:"
  echo "  /opt/homebrew/opt/python@3.12/bin/python3.12 -m venv .buildvenv"
  echo "  .buildvenv/bin/pip install -r build/requirements-build.txt"
  exit 1
fi

# --- 1. bake the key ------------------------------------------------------

if [ ! -f .env ]; then
  echo "No .env found. It must contain GEMINI_API_KEY=..."
  exit 1
fi

KEY="$(grep -E '^GEMINI_API_KEY=' .env | head -1 | cut -d= -f2- | tr -d '"'"'"' \r\n')"
if [ -z "$KEY" ]; then
  echo "GEMINI_API_KEY is empty in .env"
  exit 1
fi

cat > app/bundled_key.py <<EOF
# GENERATED BY build/build.sh — DO NOT COMMIT, DO NOT EDIT.
#
# The key is frozen into the app so the tester never handles one. It is
# recoverable by anyone who unpacks the bundle, so treat a shipped app as
# equivalent to sharing the key: rotate it if the app leaves the team.
GEMINI_API_KEY = "${KEY}"
EOF
echo "→ key baked (…${KEY: -4})"

# --- 2. icon --------------------------------------------------------------

if [ ! -f build/icon.icns ]; then
  "$PY" build/make_icon.py
fi

# --- 3. freeze ------------------------------------------------------------

rm -rf build/hecate dist/Hecate dist/Hecate.app
"$PY" -m PyInstaller --noconfirm --clean \
  --distpath dist --workpath build/hecate \
  build/hecate.spec

# --- 4. sign --------------------------------------------------------------
#
# Sign nested code first, then the bundle: signing the outer bundle seals a
# hash of everything inside it, so anything signed afterwards invalidates it.

find "$APP" -type f \( -name "*.dylib" -o -name "*.so" \) -print0 \
  | xargs -0 -n1 codesign --force --sign - --timestamp=none 2>/dev/null || true

codesign --force --deep --sign - --timestamp=none "$APP"

echo
echo "→ verifying signature"
codesign --verify --deep --strict --verbose=1 "$APP" 2>&1 | sed 's/^/   /'

# spctl will REJECT an ad-hoc signature — that is expected and is not a
# failure. It is printed so the state is visible rather than surprising.
echo
echo "→ Gatekeeper assessment (a rejection here is expected for ad-hoc):"
spctl --assess --type execute --verbose=2 "$APP" 2>&1 | sed 's/^/   /' || true

SIZE="$(du -sh "$APP" | cut -f1)"
ARCH="$(lipo -archs "$APP/Contents/MacOS/Hecate" 2>/dev/null || echo unknown)"

echo
echo "Built $APP  ($SIZE, $ARCH)"
echo
echo "Next: ./build/package.sh   to make the handover copy"

# --- 5. deployment-target guard ------------------------------------------
#
# The build machine's macOS is NOT the target's. Homebrew's Python compiles
# against whatever this Mac runs, which once produced a bundle demanding
# macOS 26 that died silently on a Ventura 13.3 machine with no error dialog,
# because Info.plist still claimed 11.0. Never ship without checking.

MAXOS=$(find "$APP" -type f \( -name "*.so" -o -name "*.dylib" -o -name "Python" \) \
        -exec sh -c 'otool -l "$1" 2>/dev/null | grep minos | head -1 | awk "{print \$2}"' _ {} \; \
        | sort -V | tail -1)
echo
echo "→ minimum macOS required by this bundle: ${MAXOS:-unknown}"
case "$MAXOS" in
  11.0|12.*) echo "   fine for any Apple Silicon Mac" ;;
  *) echo "   WARNING: this will NOT launch on a Mac older than $MAXOS."
     echo "   Build against /Library/Frameworks/Python.framework (python.org),"
     echo "   not Homebrew, and force macosx_11_0 wheels for numpy/pandas." ;;
esac
